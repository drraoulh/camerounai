export function getDestinationById(id: string) {
  return destinations.find((d) => d.id === id);
}

export function searchDestinations(query: string) {
  const q = query.toLowerCase();
  return destinations.filter((d) =>
    [
      d.name,
      d.nameEn,
      d.city,
      d.cityEn,
      d.region,
      d.regionEn,
      d.culturalZone,
      d.category,
      d.descriptionFr,
      d.descriptionEn,
      ...d.activities,
      ...d.ecoTags,
    ]
      .join(" ")
      .toLowerCase()
      .includes(q),
  );
}
